export function uiText(locale: Locale, text: string): string {
  if (locale === "ru" && text === "Organizer profile not found") return "Профиль организатора не найден";
  if (locale === "ru") return text;
  const trimmed = text.trim();
  const translated = kazakh[text] ?? kazakh[trimmed];
  if (translated === undefined) return text;
  return kazakh[text] !== undefined ? translated : text.replace(trimmed, translated);
}
